BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('MODERACION_ACCION', 'COMENTARIO', 'TEMA', 'CATEGORIA')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

CREATE TABLE CATEGORIA (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE      VARCHAR2(80)  NOT NULL,
    DESCRIPCION VARCHAR2(255),
    CONSTRAINT UQ_CATEGORIA_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE TEMA (
    ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TITULO         VARCHAR2(150)  NOT NULL,
    CONTENIDO      VARCHAR2(4000) NOT NULL,
    FECHA_CREACION TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO         VARCHAR2(20)   DEFAULT 'ACTIVO' NOT NULL,
    MOTIVO_BANEO   VARCHAR2(500),
    USUARIO_ID     NUMBER         NOT NULL,
    CATEGORIA_ID   NUMBER         NOT NULL,
    CONSTRAINT CK_TEMA_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BANEADO')),
    CONSTRAINT FK_TEMA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_TEMA_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIA (ID)
);

CREATE TABLE COMENTARIO (
    ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONTENIDO    VARCHAR2(1000) NOT NULL,
    FECHA        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO       VARCHAR2(20)   DEFAULT 'ACTIVO' NOT NULL,
    MOTIVO_BANEO VARCHAR2(500),
    TEMA_ID      NUMBER         NOT NULL,
    USUARIO_ID   NUMBER         NOT NULL,
    CONSTRAINT CK_COMENTARIO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BANEADO')),
    CONSTRAINT FK_COMENTARIO_TEMA FOREIGN KEY (TEMA_ID) REFERENCES TEMA (ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMENTARIO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID) ON DELETE CASCADE
);

CREATE INDEX IX_TEMA_CATEGORIA ON TEMA (CATEGORIA_ID, ESTADO);
CREATE INDEX IX_TEMA_USUARIO ON TEMA (USUARIO_ID);
CREATE INDEX IX_COMENTARIO_TEMA ON COMENTARIO (TEMA_ID, ESTADO);

